export function getExtensiveFallback(category: string) {
  // Try to match the category closely
  const matchKey = Object.keys(fallbackCreatorsDb).find(k => k.toLowerCase() === category.toLowerCase());
  
  let pool = [];
  if (matchKey) {
    pool = fallbackCreatorsDb[matchKey];
  } else {
    // Generate dynamically context-aware mock creators for the specific niche!
    const names = ["Pro", "Master", "Daily", "Insights", "Hacks", "Central", "Hub", "Expert", "Guru", "Network", "World", "Trends", "Life", "Diary", "Secrets"];
    pool = Array.from({ length: 15 }).map((_, i) => {
      const randomWord = names[Math.floor(Math.random() * names.length)];
      return {
        id: `mock_${category.replace(/\s+/g, '')}_${i}`,
        name: `${category} ${randomWord} ${i + 1}`,
        subscribers: 50000 + Math.floor(Math.random() * 5000000),
        totalViews: 1000000 + Math.floor(Math.random() * 100000000),
        videoCount: 50 + Math.floor(Math.random() * 800)
      };
    });
  }

  return pool.map((c: any, index: number) => {
    const avgViews = c.videoCount > 0 ? Math.floor(c.totalViews / c.videoCount) : 0;
    let score = 85 + Math.floor(Math.random() * 15); // High score for top creators
    
    const cleanName = c.name.replace(/\s+/g, '');
    const isCopiedId = c.id === "UC-xH_H49p_X_gQ_W_M_H_Q" || c.id.startsWith("mock_");
    const uniqueId = isCopiedId ? `fallback-${cleanName}-${index}` : c.id;
    
    // Fix: unavatar.io is unreliable and returning 404s. Use Dicebear purely for fallback avatars to ensure they render beautifully.
    const avatarUrl = `https://api.dicebear.com/7.x/avataaars/svg?seed=${encodeURIComponent(c.name)}&backgroundColor=e2e8f0`;

    return {
      id: uniqueId,
      name: c.name,
      // Fix: Use unavatar to securely pull YouTube channel avatars directly
      avatar: avatarUrl,
      description: `Top tier creator in the ${category} space with massive growth.`,
      subscribers: c.subscribers,
      totalViews: c.totalViews,
      videoCount: c.videoCount,
      avgViews: avgViews,
      growthRate: score > 95 ? "Explosive" : "High",
      uploadFrequency: "Weekly",
      score: score,
      category: category,
      platform: "YouTube",
      url: `https://youtube.com/results?search_query=${encodeURIComponent(c.name)}`
    };
  }).sort((a: any, b: any) => b.subscribers - a.subscribers);
}
